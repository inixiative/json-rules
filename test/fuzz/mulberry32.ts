/** A seeded 32-bit generator for the fuzz tests: integer math throughout (Math.imul), so every seed
 *  walks its own full-period stream — a floating-point LCG collapses seeds into one short cycle. */
export const mulberry32 = (seed: number): (() => number) => {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
